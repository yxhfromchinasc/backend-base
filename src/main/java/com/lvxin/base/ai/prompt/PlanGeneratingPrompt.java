    @Override
    public String generateSystemPrompt(Object context) {
        TravelRequirement requirement = (TravelRequirement) context;
        if (requirement == null) {
            throw new IllegalArgumentException("需求信息不能为空");
        }

        String destination = requirement.getDestinations().isEmpty()
                ? "目的地待定"
                : String.join("、", requirement.getDestinations());
        String startDate = requirement.getStartDate() != null
                ? requirement.getStartDate().toString()
                : "待定";
        String endDate = requirement.getEndDate() != null
                ? requirement.getEndDate().toString()
                : "待定";

        return String.format(
                SYSTEM_PROMPT_TEMPLATE,
                requirement.getSummary(),
                destination,
                startDate,
                endDate,
                endDate
        );
    }
